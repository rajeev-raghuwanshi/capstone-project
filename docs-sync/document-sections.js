const fs = require('node:fs');
const { createHash } = require('node:crypto');
const path = require('node:path');

const REPOSITORY_ROOT = path.resolve(__dirname, '..');

function canonicalize(value) {
  if (Array.isArray(value)) {
    return value.map(canonicalize);
  }
  if (value !== null && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value).sort().map((key) => [key, canonicalize(value[key])]),
    );
  }
  return value;
}

function contractId(contractPath) {
  return path.posix.basename(contractPath, '.json');
}

function responseCodes(route) {
  return [...route.successResponses, ...route.otherResponses]
    .map((status) => `\`${status}\``)
    .join(', ');
}

function renderSummary(id, contract) {
  if (id === 'routes') {
    const rows = contract.routes.map((route) => [
      `\`${route.method}\``,
      `\`${route.path}\``,
      route.purpose,
      route.inputs.length ? route.inputs.map((input) => `\`${input}\``).join(', ') : 'None',
      responseCodes(route),
    ]);
    return [
      '| Method | Path | Purpose | Inputs | Responses |',
      '| --- | --- | --- | --- | --- |',
      ...rows.map((row) => `| ${row.join(' | ')} |`),
    ].join('\n');
  }

  if (id === 'product') {
    const rows = contract.fields.map((field) => {
      const requiredness = field.required ? 'Required' : 'Optional';
      const validation = field.currency
        ? `${field.currency}; positive; at most ${field.maxFractionDigits} decimal places`
        : field.required
          ? 'Trimmed; non-empty'
          : `Trimmed; blank values: ${field.blankValue}`;
      return `| \`${field.inputName}\` | \`${field.storedName}\` | ${requiredness} | ${validation} |`;
    });
    return [
      `Product ID: \`${contract.id.format}\`, generated by \`${contract.id.generatedBy}\`, immutable.`,
      '',
      '| Input | Stored field | Requiredness | Validation |',
      '| --- | --- | --- | --- |',
      ...rows,
    ].join('\n');
  }

  if (id === 'persistence') {
    return [
      `- File: \`${contract.filePath}\` (${contract.format}).`,
      `- Missing file: \`${contract.missingFileBehavior}\`.`,
      `- Invalid data: \`${contract.invalidDataBehavior}\` using \`${contract.storageErrorName}\`.`,
      `- In-process operation serialization: ${contract.serializeOperationsInProcess ? 'enabled' : 'disabled'}.`,
      `- Write strategy: \`${contract.writeStrategy}\`.`,
      `- Multiple-process coordination: ${contract.coordinateMultipleProcesses ? 'enabled' : 'not provided'}.`,
    ].join('\n');
  }

  if (id === 'setup') {
    return [
      `- Minimum Node.js major version: ${contract.nodeMinimumMajor}.`,
      `- Listen on \`${contract.host}:${contract.defaultPort}\`; override the port with \`${contract.portEnvironmentVariable}\`.`,
      `- Commands: install \`${contract.commands.install}\`, start \`${contract.commands.start}\`, test \`${contract.commands.test}\`.`,
      `- Runtime dependencies: ${contract.dependencies.map((dependency) => `\`${dependency}\``).join(', ')}.`,
    ].join('\n');
  }

  throw new Error(`Unsupported documentation contract: ${id}`);
}

function renderContractSection(contractPath, contract) {
  const id = contractId(contractPath);
  const canonicalJson = JSON.stringify(canonicalize(contract));
  const fingerprint = createHash('sha256').update(canonicalJson).digest('hex');

  return [
    `<!-- docs-sync:begin ${id} -->`,
    `### Generated ${id} contract`,
    '',
    renderSummary(id, contract),
    '',
    `Contract SHA-256: \`${fingerprint}\`.`,
    `<!-- docs-sync:end ${id} -->`,
  ].join('\n');
}

function extractContractSection(documentText, id) {
  const normalizedDocument = documentText.replace(/\r\n/g, '\n');
  const escapedId = id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const expression = new RegExp(
    `<!-- docs-sync:begin ${escapedId} -->[\\s\\S]*?<!-- docs-sync:end ${escapedId} -->`,
    'g',
  );
  const matches = normalizedDocument.match(expression) || [];
  return matches.length === 1 ? matches[0] : null;
}

function compareContractSection(documentText, id, expectedSection) {
  const actualSection = extractContractSection(documentText, id);
  if (actualSection === null) {
    return { matches: false, reason: 'missing-or-duplicate-generated-section' };
  }
  if (actualSection !== expectedSection) {
    return { matches: false, reason: 'generated-section-mismatch' };
  }
  return { matches: true, reason: null };
}

function loadContract(contractPath, repositoryRoot = REPOSITORY_ROOT) {
  const resolvedRoot = path.resolve(repositoryRoot);
  const fullPath = path.resolve(resolvedRoot, contractPath);
  if (!fullPath.startsWith(`${resolvedRoot}${path.sep}`)) {
    throw new Error(`Contract path escapes repository root: ${contractPath}`);
  }
  return JSON.parse(fs.readFileSync(fullPath, 'utf8'));
}

module.exports = {
  REPOSITORY_ROOT,
  compareContractSection,
  extractContractSection,
  loadContract,
  renderContractSection,
};